# ==========================================================
# Randomization distance settings
# ==========================================================
# Random points are generated by:
#   1. choosing a random skeleton coordinate
#   2. choosing a random 3D direction
#   3. choosing a random radius between MIN_DISTANCE_UM and MAX_DISTANCE_UM
#   4. placing the point at that offset from the selected skeleton coordinate
#
# Examples:
#   MIN_DISTANCE_UM = 0.0
#   MAX_DISTANCE_UM = 5.0
#     -> points are placed 0 to 5 um away from the chosen skeleton coordinate
#
#   MIN_DISTANCE_UM = 5.0
#   MAX_DISTANCE_UM = 5.0
#     -> points are placed exactly 5 um away from the chosen skeleton coordinate
#
# Note:
#   By default, the distance range is measured relative to the chosen skeleton
#   coordinate, preserving the behavior of your original script.
#
#   If ENFORCE_NEAREST_SKELETON_RANGE = True, the script also checks the nearest
#   skeleton coordinate after generation and rejects points outside the range.
#   This can be slower, especially for narrow or exact ranges like 5.0-5.0.
# ==========================================================
MIN_DISTANCE_UM = 0.0
MAX_DISTANCE_UM = 5.0

ENFORCE_NEAREST_SKELETON_RANGE = False
NEAREST_RANGE_TOLERANCE_UM = 1e-6
MAX_REJECTION_ATTEMPTS_PER_POINT = 10000

