def sanitize_name(name):
    name = str(name).strip()

    if name == "":
        name = "unknown"

    for bad in ["\\", "/", ":", "*", "?", '"', "<", ">", "|"]:
        name = name.replace(bad, "_")

    name = re.sub(r"\s+", "_", name)
    return name


def is_inside_skipped_folder(path):
    lower_parts = [str(part).lower() for part in Path(path).parts]
    joined = "/".join(lower_parts)

    return any(keyword.lower() in joined for keyword in SKIP_FOLDER_KEYWORDS)


def safe_to_csv(df, path, index=False):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)

    try:
        if path.exists() and not OVERWRITE_EXISTING:
            print(f"  Skipping existing file: {path.name}")
            return path
        df.to_csv(path, index=index)
        return path

    except PermissionError:
        from datetime import datetime

        stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        fallback = path.with_name(f"{path.stem}_{stamp}{path.suffix}")
        df.to_csv(fallback, index=index)
        print(f"  Permission denied writing {path.name}; saved as {fallback.name}")
        return fallback


def safe_to_excel(df, path, index=False, sheet_name="Sheet1"):
    if not WRITE_EXCEL:
        return None

    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)

    try:
        if path.exists() and not OVERWRITE_EXISTING:
            print(f"  Skipping existing file: {path.name}")
            return path
        df.to_excel(path, index=index, sheet_name=sheet_name[:31])
        return path

    except PermissionError:
        from datetime import datetime

        stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        fallback = path.with_name(f"{path.stem}_{stamp}{path.suffix}")
        df.to_excel(fallback, index=index, sheet_name=sheet_name[:31])
        print(f"  Permission denied writing {path.name}; saved as {fallback.name}")
        return fallback

    except Exception as e:
        print(f"  Could not write Excel file {path}: {e}")
        return None


def write_csv_and_excel(df, csv_path, xlsx_path=None, sheet_name="Sheet1", index=False):
    csv_out = safe_to_csv(df, csv_path, index=index)
    xlsx_out = None

    if xlsx_path is not None:
        xlsx_out = safe_to_excel(df, xlsx_path, index=index, sheet_name=sheet_name)

    return csv_out, xlsx_out


def find_raw_spot_files(parent):
    files = []

    for ext in ["*.csv", "*.xlsx", "*.xlsm", "*.xls"]:
        files.extend(Path(parent).rglob(ext))

    out = []

    for p in sorted(set(files)):
        if not p.is_file():
            continue

        if p.name.startswith("~$"):
            continue

        if is_inside_skipped_folder(p):
            continue

        if RAW_SPOT_FILE_REQUIRED_SUBSTRING.lower() not in p.name.lower():
            continue

        lower_name = p.name.lower()

        generated_terms = [
            "summary",
            "spot_counts",
            "nn_distance",
            "random",
            "converted",
            "colocalization",
            "surface_distances",
            "nearest_node",
            "histogram",
            "distribution",
        ]

        if any(term in lower_name for term in generated_terms):
            continue

        out.append(p)

    return out


def read_spot_table(path):
    path = Path(path)
    suffix = path.suffix.lower()

    if suffix == ".csv":
        # smallFISH output is often semicolon-delimited.
        attempts = [
            {"sep": ";"},
            {"sep": ","},
            {"sep": "\t"},
            {"sep": None, "engine": "python"},
        ]

        best = None
        best_cols = -1

        for kwargs in attempts:
            try:
                df = pd.read_csv(path, **kwargs)
                df.columns = [str(c).strip() for c in df.columns]

                if df.shape[1] > best_cols:
                    best = df
                    best_cols = df.shape[1]

                try:
                    find_intensity_column(df)
                    return df
                except Exception:
                    pass

            except Exception:
                pass

        if best is not None:
            return best

        raise ValueError(f"Could not read CSV file: {path}")

    if suffix in [".xlsx", ".xlsm", ".xls"]:
        df = pd.read_excel(path)
        df.columns = [str(c).strip() for c in df.columns]
        return df

    raise ValueError(f"Unsupported file type: {path}")


def normalize_column_name(col):
    s = str(col).strip().lower()
    s = s.replace("µ", "u")
    s = s.replace("μ", "u")
    s = re.sub(r"[^a-z0-9]+", "", s)
    return s


def find_intensity_column(df):
    if INTENSITY_COLUMN is not None:
        if INTENSITY_COLUMN in df.columns:
            return INTENSITY_COLUMN

        raise ValueError(
            f"INTENSITY_COLUMN='{INTENSITY_COLUMN}' was not found. "
            f"Available columns: {list(df.columns)}"
        )

    normalized = {col: normalize_column_name(col) for col in df.columns}
    candidate_norms = {normalize_column_name(c) for c in INTENSITY_COLUMN_CANDIDATES}

    for col, norm in normalized.items():
        if norm in candidate_norms:
            return col

    # Fallback: any column containing "intensity".
    for col, norm in normalized.items():
        if "intensity" in norm:
            return col

    raise ValueError(
        "Could not identify an intensity column. "
        f"Available columns: {list(df.columns)}"
    )


def extract_cell_index(path_or_name):
    stem = Path(str(path_or_name)).stem

    # Typical smallFISH output: spots_extractions_..._000.csv
    m = re.search(r"[_\-](\d{1,4})$", stem)
    if m:
        return int(m.group(1))

    # Fallback: cell_000 style.
    m = re.search(r"(?:^|[_\-])cell[_\-]?(\d{1,4})(?:[_\-]|$)", stem, flags=re.IGNORECASE)
    if m:
        return int(m.group(1))

    return None


def find_series_folder(path):
    p = Path(path)

    for parent in [p.parent] + list(p.parents):
        if parent.name.lower().startswith("series"):
            return parent

    return None


def infer_condition_label(path, parent_folder, series_folder):
    """
    Experimental condition label.

    If selected parent contains:
      yWL333/MS2(ATP3)/Series 4/...
    condition label becomes:
      yWL333__MS2(ATP3)

    If selected parent is itself the condition folder and contains:
      Series 4/...
    condition label becomes selected parent folder name.
    """
    path = Path(path)
    parent_folder = Path(parent_folder)

    if series_folder is None:
        try:
            rel_parts = path.relative_to(parent_folder).parts
            if len(rel_parts) > 0:
                return sanitize_name(rel_parts[0])
        except Exception:
            pass

        return sanitize_name(parent_folder.name)

    try:
        rel_series = Path(series_folder).relative_to(parent_folder)
        before_series = list(rel_series.parts[:-1])

        if len(before_series) == 0:
            return sanitize_name(parent_folder.name)

        return sanitize_name("__".join(before_series))

    except Exception:
        return sanitize_name(parent_folder.name)


def infer_series_label(series_folder, parent_folder):
    if series_folder is None:
        return "unknown_series"

    try:
        rel = Path(series_folder).relative_to(parent_folder)
        return sanitize_name("__".join(rel.parts))
    except Exception:
        return sanitize_name(Path(series_folder).name)


def path_part_matches_channel(part, channel):
    p = str(part).strip().upper()
    c = str(channel).strip().upper()

    if p == c:
        return True

    if p.startswith(c + "_") or p.startswith(c + " ") or p.startswith(c + "-"):
        return True

    if re.search(rf"(^|[_\-\s\(\+]){re.escape(c)}([_\-\s\)\+]|$)", p):
        return True

    return False


def infer_rna_channel(path, series_folder=None):
    p = Path(path)

    # Prefer folders between the Series folder and spots_extraction.
    if series_folder is not None:
        try:
            rel_parts = p.relative_to(series_folder).parts

            useful_parts = []
            for part in rel_parts:
                useful_parts.append(part)
                if str(part).lower() == "spots_extraction":
                    break

            for part in useful_parts:
                for channel in KNOWN_RNA_CHANNELS:
                    if path_part_matches_channel(part, channel):
                        return channel.upper() if channel.upper() != "TIM50" else "TIM50"

        except Exception:
            pass

    # Fallback to filename/path search.
    for part in list(p.parts)[::-1]:
        for channel in KNOWN_RNA_CHANNELS:
            if path_part_matches_channel(part, channel):
                return channel.upper() if channel.upper() != "TIM50" else "TIM50"

    return "unknown_RNA"


def load_intensity_rows(file_path):
    df = read_spot_table(file_path)
    intensity_col = find_intensity_column(df)

    values = pd.to_numeric(df[intensity_col], errors="coerce")
    values = values.replace([np.inf, -np.inf], np.nan).dropna()

    if FILTER_MIN_INTENSITY is not None:
        values = values[values >= FILTER_MIN_INTENSITY]

    if FILTER_MAX_INTENSITY is not None:
        values = values[values <= FILTER_MAX_INTENSITY]

    series_folder = find_series_folder(file_path)
    condition_label = infer_condition_label(file_path, parent_folder, series_folder)
    series_label = infer_series_label(series_folder, parent_folder)
    rna_channel = infer_rna_channel(file_path, series_folder=series_folder)
    cell_index = extract_cell_index(file_path.name)

    rows = []

    for spot_i, value in enumerate(values.to_numpy(dtype=float)):
        rows.append(
            {
                "condition_label": condition_label,
                "series_label": series_label,
                "series_folder": str(series_folder) if series_folder is not None else "",
                "rna_channel": rna_channel,
                "cell_index": cell_index,
                "source_file": str(file_path),
                "source_filename": file_path.name,
                "intensity_column": intensity_col,
                "spot_row_index_after_filtering": spot_i,
                "intensity": float(value),
            }
        )

    return rows, {
        "source_file": str(file_path),
        "source_filename": file_path.name,
        "condition_label": condition_label,
        "series_label": series_label,
        "rna_channel": rna_channel,
        "cell_index": cell_index,
        "intensity_column": intensity_col,
        "raw_rows": int(len(df)),
        "finite_intensity_rows_after_filtering": int(len(values)),
    }


def summarize_group(df, group_cols):
    rows = []

    for group_values, sub in df.groupby(group_cols, dropna=False):
        if not isinstance(group_values, tuple):
            group_values = (group_values,)

        intensities = pd.to_numeric(sub["intensity"], errors="coerce").dropna()

        row = dict(zip(group_cols, group_values))
        row.update(
            {
                "n_spots": int(len(intensities)),
                "n_cells": int(sub["cell_index"].nunique()),
                "n_files": int(sub["source_file"].nunique()),
                "mean_intensity": float(intensities.mean()) if len(intensities) > 0 else np.nan,
                "median_intensity": float(intensities.median()) if len(intensities) > 0 else np.nan,
                "std_intensity": float(intensities.std(ddof=1)) if len(intensities) > 1 else np.nan,
                "sem_intensity": float(intensities.std(ddof=1) / np.sqrt(len(intensities))) if len(intensities) > 1 else np.nan,
                "min_intensity": float(intensities.min()) if len(intensities) > 0 else np.nan,
                "q25_intensity": float(intensities.quantile(0.25)) if len(intensities) > 0 else np.nan,
                "q75_intensity": float(intensities.quantile(0.75)) if len(intensities) > 0 else np.nan,
                "max_intensity": float(intensities.max()) if len(intensities) > 0 else np.nan,
            }
        )

        rows.append(row)

    return pd.DataFrame(rows)


