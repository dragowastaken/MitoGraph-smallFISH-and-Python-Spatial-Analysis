def get_hist_range(values):
    values = np.asarray(values, dtype=float)
    values = values[np.isfinite(values)]

    if len(values) == 0:
        return None

    if INTENSITY_XMIN is None and INTENSITY_XMAX is None:
        return None

    left = INTENSITY_XMIN if INTENSITY_XMIN is not None else float(np.min(values))
    right = INTENSITY_XMAX if INTENSITY_XMAX is not None else float(np.max(values))

    if left >= right:
        return None

    return (left, right)


def save_histogram(values, out_path, title, xlabel="RNA spot intensity"):
    values = np.asarray(values, dtype=float)
    values = values[np.isfinite(values)]

    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    if len(values) == 0:
        note = out_path.with_suffix(".txt")
        note.write_text(f"No finite intensity values available for:\n{title}\n", encoding="utf-8")
        return note

    plt.figure(figsize=(8, 6), facecolor="white")
    plt.hist(values, bins=HISTOGRAM_BINS, range=get_hist_range(values), edgecolor="black")
    plt.xlabel(xlabel)
    plt.ylabel("RNA spot count")
    plt.title(title)
    plt.tight_layout()
    plt.savefig(out_path, dpi=300, facecolor="white", bbox_inches="tight")
    plt.close()

    return out_path


def save_log10_histogram(values, out_path, title):
    values = np.asarray(values, dtype=float)
    values = values[np.isfinite(values)]
    values = values[values > 0]

    if len(values) == 0:
        note = Path(out_path).with_suffix(".txt")
        note.parent.mkdir(parents=True, exist_ok=True)
        note.write_text(f"No positive intensity values available for log10 plot:\n{title}\n", encoding="utf-8")
        return note

    log_values = np.log10(values)

    return save_histogram(
        log_values,
        out_path,
        title=title,
        xlabel="log10 RNA spot intensity",
    )


def save_group_histograms(df, group_cols, output_folder, filename_prefix):
    plot_rows = []

    for group_values, sub in df.groupby(group_cols, dropna=False):
        if not isinstance(group_values, tuple):
            group_values = (group_values,)

        group_dict = dict(zip(group_cols, group_values))

        label_parts = [f"{col}_{sanitize_name(val)}" for col, val in group_dict.items()]
        label = "__".join(label_parts)

        title_parts = [f"{col}: {val}" for col, val in group_dict.items()]
        title = " | ".join(title_parts)

        intensities = pd.to_numeric(sub["intensity"], errors="coerce").dropna().to_numpy(dtype=float)

        out_dir = Path(output_folder)
        out_dir.mkdir(parents=True, exist_ok=True)

        png_path = out_dir / f"{filename_prefix}__{label}.png"
        saved = save_histogram(
            intensities,
            png_path,
            title=f"RNA intensity histogram | {title}",
        )

        plot_row = dict(group_dict)
        plot_row.update(
            {
                "plot_type": "raw_intensity_histogram",
                "n_spots": int(len(intensities)),
                "plot_file": str(saved),
            }
        )
        plot_rows.append(plot_row)

        if MAKE_LOG10_HISTOGRAMS:
            log_png_path = out_dir / f"{filename_prefix}__{label}__log10.png"
            log_saved = save_log10_histogram(
                intensities,
                log_png_path,
                title=f"log10 RNA intensity histogram | {title}",
            )

            log_row = dict(group_dict)
            log_row.update(
                {
                    "plot_type": "log10_intensity_histogram",
                    "n_spots": int(np.sum(np.asarray(intensities) > 0)),
                    "plot_file": str(log_saved),
                }
            )
            plot_rows.append(log_row)

    return plot_rows


def write_multi_sheet_workbook(path, sheet_to_df):
    if not WRITE_EXCEL:
        return None

    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)

    try:
        if path.exists() and not OVERWRITE_EXISTING:
            print(f"  Skipping existing workbook: {path.name}")
            return path

        with pd.ExcelWriter(path, engine="openpyxl") as writer:
            for sheet_name, df in sheet_to_df.items():
                safe_sheet = str(sheet_name)[:31]
                df.to_excel(writer, sheet_name=safe_sheet, index=False)

        return path

    except PermissionError:
        from datetime import datetime

        stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        fallback = path.with_name(f"{path.stem}_{stamp}{path.suffix}")

        with pd.ExcelWriter(fallback, engine="openpyxl") as writer:
            for sheet_name, df in sheet_to_df.items():
                safe_sheet = str(sheet_name)[:31]
                df.to_excel(writer, sheet_name=safe_sheet, index=False)

        print(f"  Permission denied writing {path.name}; saved as {fallback.name}")
        return fallback

    except Exception as e:
        print(f"  Could not write workbook {path}: {e}")
        return None


